#[cfg(target_os = "linux")]
mod compilation {
	use crate::shader::glsl_compile;

	/// The `SpirvCompiler` struct holds one shaderc compiler for every GLSL compile its owner runs.
	///
	/// shaderc rebuilds glslang's built-in symbol tables for every new compiler, so an owner that compiles many shaders,
	/// such as the platform toolchain, keeps one and lends it. shaderc allows concurrent compiles on one compiler. Next,
	/// call [`Self::compile`].
	pub(crate) struct SpirvCompiler {
		/// The shaderc compiler, or why it could not be created, which every compile then reports.
		compiler: Result<shaderc::Compiler, String>,
	}

	impl SpirvCompiler {
		/// Creates the shaderc compiler. A failure is kept and reported by each later compile.
		pub(crate) fn new() -> Self {
			let compiler = shaderc::Compiler::new().map_err(|error| {
				format!(
					"Failed to create the shaderc compiler. The most likely cause is that the shaderc library failed to initialize. Check that the shaderc library from the Vulkan SDK is installed and loadable. Error: {error}"
				)
			});
			Self { compiler }
		}

		/// Describes the linked shaderc build and the options [`Self::compile`] passes.
		///
		/// Baked shader reuse hashes this text, so a stored SPIR-V binary is only reused by the compiler that produced it.
		/// shaderc reports no release version, only the SPIR-V version it targets, so the identity comes from compiling
		/// [`SPIRV_IDENTITY_PROBE`]: its header records glslang's generator version, which glslang bumps whenever its code
		/// generation changes, and its full hash also changes when the bundled optimizer emits different code.
		pub(crate) fn identity(&self) -> Result<String, String> {
			let probe = self.compile(SPIRV_IDENTITY_PROBE, "spirv_identity_probe")?;

			// SPIR-V header words are magic, version, generator, bound, and schema.
			let generator = probe
				.get(8..12)
				.and_then(|word| word.try_into().ok())
				.map(u32::from_le_bytes)
				.ok_or_else(|| {
					"Failed to read the shaderc identity probe header. The most likely cause is that shaderc returned an empty SPIR-V binary."
					.to_string()
				})?;
			let (version, revision) = shaderc::get_spirv_version();

			Ok(format!(
				"shaderc spirv={version:#x}.{revision}; generator={generator:#010x}; probe={:x}; vulkan=1.4; target=spirv1.6; optimization=performance; debug_info={}",
				md5::compute(&probe),
				cfg!(debug_assertions)
			))
		}

		/// Compiles GLSL source generated by the BESL GLSL backend into a SPIR-V binary.
		///
		/// `name` appears in compiler diagnostics and debug information.
		pub(crate) fn compile(&self, glsl: &str, name: &str) -> Result<Box<[u8]>, String> {
			let compiler = self.compiler.as_ref().map_err(Clone::clone)?;
			// Keep `Self::identity` in sync with these options, because baked shader reuse relies on it.
			let mut options = shaderc::CompileOptions::new().unwrap();
			options.set_optimization_level(shaderc::OptimizationLevel::Performance);
			options.set_target_env(shaderc::TargetEnv::Vulkan, shaderc::EnvVersion::Vulkan1_4 as u32);
			if cfg!(debug_assertions) {
				options.set_generate_debug_info();
			}
			// Raster passes flip y with a negative viewport height, so the compiler leaves positions as the shader writes them.
			options.set_target_spirv(shaderc::SpirvVersion::V1_6);

			match compiler.compile_into_spirv(glsl, shaderc::ShaderKind::InferFromSource, name, "main", Some(&options)) {
				Ok(binary) => Ok(Box::from(binary.as_binary_u8())),
				Err(err) => Err(glsl_compile::pretty_format_glslang_error_string(&err.to_string(), name, glsl)),
			}
		}
	}

	/// Exercises branching, loops, calls, and buffer access so optimizer changes are likely to change the probe binary.
	const SPIRV_IDENTITY_PROBE: &str = r#"#version 450
#pragma shader_stage(compute)
layout(local_size_x = 64) in;
layout(set = 0, binding = 0, std430) buffer Data { float values[]; } data;

float shade(float value) {
	return value > 0.5 ? sqrt(value) : value * value + 0.25;
}

void main() {
	uint index = gl_GlobalInvocationID.x;
	float accumulated = 0.0;

	for (uint offset = 0; offset < 4; ++offset) {
		accumulated += shade(data.values[index + offset]);
	}

	data.values[index] = accumulated;
}
"#;

	#[cfg(test)]
	mod tests {
		use super::SpirvCompiler;

		#[test]
		fn compiler_identity_records_the_glslang_generator_version() {
			let compiler = SpirvCompiler::new();
			let identity = compiler.identity().expect("the shaderc identity probe should compile");

			// Khronos tool ID 13 is shaderc over glslang; the low half is glslang's generator version.
			assert!(identity.contains("generator=0x000d"), "unexpected identity: {identity}");
			assert_eq!(compiler.identity().as_deref(), Ok(identity.as_str()));
		}
	}
}

#[cfg(target_os = "linux")]
pub(crate) use compilation::SpirvCompiler;
