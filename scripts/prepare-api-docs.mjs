import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve, sep } from 'node:path';

const [stagingArgument] = process.argv.slice(2);
if (!stagingArgument) {
	throw new Error('Missing generated Markdown directory. Pass the cargo-docs-md output path.');
}

const staging = resolve(stagingArgument);
const apiRoutePrefix = '/docs/api/latest';
const pages = await collectMarkdownPages(staging);
const pageData = await Promise.all(pages.map(async (page) => {
	const relativePage = relative(staging, page).split(sep).join('/');
	const pagePath = relativePage.slice(0, -'/index.md'.length);
	return {
		page,
		relativePage,
		pagePath,
		route: `${apiRoutePrefix}/${pagePath}`,
		markdown: await readFile(page, 'utf8'),
	};
}));
const anchorsByRoute = new Map(
	pageData.map(({ route, markdown }) => [route, renderedAnchors(markdown)]),
);
const globalAnchors = indexGlobalAnchors(anchorsByRoute);

for (const data of pageData) {
	const { page, relativePage, pagePath, route: pageRoute } = data;
	const pathSegments = pagePath.split('/');
	const crateName = pathSegments[0];
	const title = pathSegments.at(-1);

	let { markdown } = data;

	// rustdoc fence tags describe test behavior. Shiki needs the real language.
	markdown = markdown.replace(
		/^```(?:rust,)?(?:(?:compile_fail|ignore|no_run|should_panic|edition20(?:15|18|21|24)|E\d+),?)+$/gm,
		'```rust',
	);

	// cargo-docs-md targets files, while Fumadocs exposes extensionless routes.
	// Absolute routes also keep deep module links inside the generated API tree.
	markdown = markdown.replace(
		/\]\(([^)\s]+\.md(?:#[^)\s]*)?)\)/g,
		(match, destination) => {
			const hashIndex = destination.indexOf('#');
			const target = hashIndex === -1
				? destination
				: destination.slice(0, hashIndex);
			const fragment = hashIndex === -1 ? '' : destination.slice(hashIndex);
			const absoluteTarget = resolve(dirname(page), target);
			const relativeTarget = relative(staging, absoluteTarget).split(sep).join('/');

			if (relativeTarget.startsWith('../')) return match;

			const route = relativeTarget === 'index.md'
				? apiRoutePrefix
				: `${apiRoutePrefix}/${relativeTarget.replace(/\/index\.md$/, '')}`;
			return `](${route}${fragment})`;
		},
	);

	markdown = rewriteApiFragments(
		markdown,
		pageRoute,
		anchorsByRoute,
		globalAnchors,
	);

	markdown = formatImplementationMembers(markdown);

	const frontmatter = [
		'---',
		`title: "${title}"`,
		`description: "Generated Rust API reference for ${crateName}."`,
		'---',
		'',
		'<!-- Generated by scripts/generate-api-docs.sh. Do not edit. -->',
		'',
	].join('\n');

	await writeFile(page, frontmatter + markdown);
}

// cargo-docs-md emits methods and associated items as inline code in a list.
// Keep the list structure and descriptions, but let Fumadocs render each Rust
// signature with its normal highlighted, scrollable code-block component.
function formatImplementationMembers(markdown) {
	return markdown.replace(
		/^([ \t]*)- (?:<span id="[^"]+"><\/span>)?`([^`\n]+)`(?: — (.+))?$/gm,
		(match, indentation, signature, relatedItems) => {
			const blockIndentation = `${indentation}  `;
			const related = relatedItems
				? `\n\n${blockIndentation}Related: ${relatedItems}`
				: '';
			return `${indentation}- \`\`\`rust\n${blockIndentation}${signature}\n${blockIndentation}\`\`\`${related}`;
		},
	);
}

// cargo-docs-md and Fumadocs use different heading slugs: cargo-docs-md turns
// underscores into hyphens, while Fumadocs preserves them. Record both forms
// so links can be translated without parsing rustdoc JSON a second time.
function renderedAnchors(markdown) {
	const anchors = new Map();
	const duplicateCounts = new Map();

	for (const match of markdown.matchAll(/^#{1,6}\s+(.+?)\s*$/gm)) {
		const heading = match[1]
			.replace(/`+/g, '')
			.replace(/!?(?:\[([^\]]*)\])\([^)]*\)/g, '$1')
			.replace(/[*~]/g, '');
		const baseAnchor = githubLikeSlug(heading);
		const duplicate = duplicateCounts.get(baseAnchor) ?? 0;
		const renderedAnchor = duplicate === 0 ? baseAnchor : `${baseAnchor}-${duplicate}`;
		duplicateCounts.set(baseAnchor, duplicate + 1);

		anchors.set(renderedAnchor, renderedAnchor);
		anchors.set(renderedAnchor.replaceAll('_', '-'), renderedAnchor);

		// Generic item headings include their parameters in the rendered slug,
		// while cargo-docs-md links to the bare Rust item name.
		const itemName = match[1].match(/^`([A-Za-z_][A-Za-z0-9_]*)/)?.[1];
		if (itemName && itemName !== 'impl') {
			const bareItemAnchor = itemName.toLowerCase();
			anchors.set(bareItemAnchor, renderedAnchor);
			anchors.set(bareItemAnchor.replaceAll('_', '-'), renderedAnchor);
		}
	}

	return anchors;
}

function githubLikeSlug(heading) {
	return heading
		.trim()
		.toLowerCase()
		.replace(/[^\p{L}\p{N}\p{M}_ -]/gu, '')
		.replace(/ /g, '-');
}

function indexGlobalAnchors(anchorsByRoute) {
	const global = new Map();
	for (const [route, anchors] of anchorsByRoute) {
		for (const [sourceAnchor, renderedAnchor] of anchors) {
			const candidates = global.get(sourceAnchor) ?? [];
			if (!candidates.some((candidate) => candidate.route === route)) {
				candidates.push({ route, renderedAnchor });
			}
			global.set(sourceAnchor, candidates);
		}
	}
	return global;
}

function rewriteApiFragments(markdown, pageRoute, anchorsByRoute, globalAnchors) {
	return markdown.replace(
		/\]\((\/docs\/api\/latest(?:\/[^#)\s]*)?)?#([^)\s]+)\)/g,
		(match, rawRoute, encodedAnchor) => {
			const targetRoute = rawRoute?.replace(/\/$/, '') || pageRoute;
			const sourceAnchor = decodeURIComponent(encodedAnchor);
			const localAnchor = anchorsByRoute.get(targetRoute)?.get(sourceAnchor);
			if (localAnchor) return `](${targetRoute}#${localAnchor})`;

			const candidates = globalAnchors.get(sourceAnchor) ?? [];
			if (candidates.length === 1) {
				const [{ route, renderedAnchor }] = candidates;
				return `](${route}#${renderedAnchor})`;
			}

			// rustdoc can link methods and hidden re-exports that cargo-docs-md does
			// not emit as headings. Keep the useful page navigation in that case.
			return `](${targetRoute})`;
		},
	);
}

async function collectMarkdownPages(directory) {
	const entries = await readdir(directory, { withFileTypes: true });
	const collected = [];

	for (const entry of entries) {
		const path = resolve(directory, entry.name);
		if (entry.isDirectory()) {
			collected.push(...await collectMarkdownPages(path));
		} else if (entry.isFile() && entry.name.endsWith('.md')) {
			collected.push(path);
		}
	}

	return collected.sort();
}
